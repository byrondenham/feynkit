"""
Lattice polytopes: the face lattice, facet inequalities and normalised volume.

A polytope P = conv(points) with integer points is described by its faces,
each given as the indices of all the points lying on it, by its facet
inequalities and by its normalised volume, all computed in integer
arithmetic.

The facets come from an integer beneath-beyond construction, or on request
from Qhull or Normaliz candidates, each verified exactly. The list is
certified complete before anything is derived from it: every edge of the
face lattice the candidates generate has two vertices, every face of
dimension at least 2 has a candidate facet, and along every chain R < F < Q
exactly two candidate facets of Q contain R. A Qhull or Normaliz list that
fails the certificate is replaced by beneath-beyond, and a failure there
raises ComputationError.

For a full-dimensional P each facet is m . x <= b with m primitive in Z^n
and pointing outwards. A lower-dimensional P is handled in its lattice chart
x = o + B c, where its points generate Z^d affinely. Its facets relative to
the affine hull are lifted to primitive ambient forms mu . x <= b, which
with the affine-hull equations cut out P; PolytopeData.facets stays empty
and PolytopeData.relative_facets holds them. Each facet also carries its
lattice index g_F, the gcd of b - m . alpha_j over the points, so that
(b, -m) / g_F is the facet form primitive with respect to the lattice ZA
generated by the homogenised points (1, alpha_j).

The normalised volume is measured in the lattice L the differences of the
points span, from a pulling triangulation of the certified face lattice.
For a full-dimensional configuration, generic coefficients and non-resonant
beta it is the holonomic rank of the associated GKZ system. Below full
dimension the rows of the homogenised A are linearly dependent, and for
generic beta the system has no non-zero solutions.
"""

