class Citations:
    """The works a document cites, in the order of first citation."""

    def __init__(self) -> None:
        self.keys: list[str] = []

    def add(self, *keys: str) -> None:
        """Record a citation of ``keys``, each of which needs a bibliography entry."""
        for key in keys:
            if key not in CITATIONS:
                raise KeyError(f"No bibliography entry for {key!r}")
            if key not in self.keys:
                self.keys.append(key)


# --- the representations and the polynomials --------------------------------


class Templates(NamedTuple):
    """The integrands of the three representations in the symbols U, F, G and nu."""

    schwinger: sp.Expr
    feynman: sp.Expr
    lee_pomeransky: sp.Expr


def integrand_templates(loop_count: int, dimension: sp.Expr) -> Templates:
    """The integrands written in U, F, G and nu, the sum of the exponents.

    The Feynman integrand leaves out the delta function, which the document
    writes into the measure, matching ``ParametrisationResult.integrand``.
    """
    u, f, g, nu = sp.symbols("U F G nu")
    loops = sp.Integer(loop_count)
    return Templates(
        schwinger=u ** (-dimension / 2) * sp.exp(-f / u),
        feynman=u ** (nu - (loops + 1) * dimension / 2) * f ** (loops * dimension / 2 - nu),
        lee_pomeransky=g ** (-dimension / 2),
    )


def split_g(g: sp.Expr, scale: sp.Symbol) -> tuple[sp.Expr, sp.Expr, int]:
    """G as ``u_part + numerator / scale**power``, the second part its F terms.

    G carries the same power of the energy scale on its F terms as F does, and
    the documents factor it out the same way.
    """
    terms = sp.Add.make_args(sp.expand(g))
    u_part = sp.Add(*[t for t in terms if scale not in t.free_symbols])
    numerator, power = factor_energy_scale(
        sp.Add(*[t for t in terms if scale in t.free_symbols]), scale
    )
    return u_part, numerator, power


