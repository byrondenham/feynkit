def join_words(items: Sequence[str]) -> str:
    """Join as 'a, b and c'."""
    if not items:
        return "none"
    if len(items) == 1:
        return items[0]
    return ", ".join(items[:-1]) + " and " + items[-1]


def count_noun(n: int, singular: str, plural: str | None = None) -> str:
    """'1 edge', '3 edges'."""
    return f"{n} {singular if n == 1 else (plural or singular + 's')}"


def signed_terms(terms: Sequence[tuple[int, str]]) -> str:
    """Join (coefficient, symbol) pairs into a signed sum, omitting zeros."""
    out = ""
    for coefficient, symbol in terms:
        if coefficient == 0:
            continue
        magnitude = abs(coefficient)
        term = symbol if magnitude == 1 else f"{magnitude} {symbol}"
        if not out:
            out = term if coefficient > 0 else f"- {term}"
        else:
            out += f" + {term}" if coefficient > 0 else f" - {term}"
    return out


def append_signed(sum_text: str, expr: sp.Expr, printer: Callable[[sp.Expr], str]) -> str:
    """Append ``expr``, printed by ``printer``, with its sign to a printed sum."""
    if expr == 0:
        return sum_text or "0"
    term = printer(expr)
    if not sum_text:
        return term
    if term.startswith("-"):
        return f"{sum_text} - {term[1:].lstrip()}"
    return f"{sum_text} + {term}"
