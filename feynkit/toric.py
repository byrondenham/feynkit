"""
Normal cones of faces, smooth orbit charts and smooth subdivisions of cones.

Let P be a lattice polytope and L the lattice its differences span, so that
P sits in the lattice chart of :func:`~feynkit.polytope.polytope_data`, with
coordinates in Z^d, d the dimension of P. The inner normal cone of a face F is
generated by the inner normals of the facets of P through F; these cones form
the inner normal fan of P (Cox, Little and Schenck, Toric Varieties, AMS 2011,
abbreviated CLS11, Thm 2.3.2, p. 77). Here the generators are the primitive
facet forms of the chart, negated, so the cone lives in the dual lattice
N = Z^d, and its rays are the facet normals, one per facet through F. The
charts live in the lattice L the point differences span, so when L has index
above 1 in Z^n the chart torus is a quotient of the ambient one.

A cone is smooth when its rays extend to a basis of N. Then its affine toric
variety U_sigma, the chart of X_P around the orbit O_F, is
C^r x (C^*)^(d-r), r the number of rays, and a Laurent polynomial G supported
on P becomes g = x^(-v) G, a polynomial in the coordinates y_1, ..., y_r of
C^r and a Laurent polynomial in the torus coordinates t_1, ..., t_(d-r); see
:class:`OrbitChart`.

A cone that is not smooth is replaced by a smooth subdivision, built in two
steps. A regular triangulation of the rays, by a random lifting of seeded
integer heights, gives simplicial cones that use no new rays. Each simplicial
cone of multiplicity above 1 is then removed by a star (stellar) subdivision
at a non-zero lattice point of its fundamental parallelepiped, applied to the
whole fan. The multiplicity of the cone it was done for drops, and the cones
it creates have strictly smaller multiplicity (CLS11 Thm 11.1.9, p. 520, and
its proof on pp. 520 and 521; the point exists by Prop. 11.1.8(b), p. 519). Only the
cone of F is subdivided: the preimage of the orbit O_F under the toric
morphism of a subdivision is the union of the orbits O_tau with tau a cone
whose relative interior lies in that of sigma (CLS11 Lemma 3.3.21(b),
p. 135).

All arithmetic is exact, on Python integers and fractions.
"""

from __future__ import annotations

import itertools
import math
import random
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
